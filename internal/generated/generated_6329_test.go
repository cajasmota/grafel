// TestFromContent_OnlyTheFirstCommentBlockIsScanned is the false-positive fix.
//
// The original design argued that the `(?m)^` anchor was enough to keep prose
// about generated code from matching. It is not: `^` is start-of-LINE, not
// start-of-FILE, and prose in source almost always starts a line. A sweep of
// ~207k files in the Go module cache flagged 8,236 files, and every sampled
// false positive fell into one of the three classes below — all of them with
// the matched line at lines 12-18, while real generator banners live at lines
// 1-5.
//
// The fix is a boundary, not a magic number: a generated-file banner is part
// of the file's HEADER, so the scan stops at the first line that is not a
// comment, blank, or a language preamble directive (shebang, <?php, <?xml).
//
// Each case below is a SYNTHETIC reproduction of the shape observed in a real
// hand-written file; no third-party file is vendored. The provenance of the
// shape is named in each case.
//
// MUTATION TARGET: widen the scan back past the first comment block (drop the
// headerBlock call in FromContent) and every case here must fail.
func TestFromContent_OnlyTheFirstCommentBlockIsScanned(t *testing.T) {
	cases := []struct {
		name string
		head string
	}{
		{
			// CLASS 1 — a generator script carrying the banner it EMITS.
			// Shape of syscall/mksysnum_linux.pl (Go toolchain source): the
			// perl script prints the banner from a heredoc at line 12. Lines
			// 1-4 are a shebang plus licence comments; line 6 is `use strict;`
			// which ends the header block.
			name: "generator-script/perl-emits-banner-from-heredoc",
			head: "#!/usr/bin/env perl\n" +
				"# Copyright 2009 The Example Authors.\n" +
				"# Use of this source code is governed by a BSD-style licence.\n" +
				"\n" +
				"use strict;\n" +
				"\n" +
				"my $command = \"mksysnum.pl \" . join(' ', @ARGV);\n" +
				"\n" +
				"print <<EOF;\n" +
				"// $command\n" +
				"// Code generated by the command above; DO NOT EDIT.\n" +
				"EOF\n",
		},
		{
			// CLASS 1 — same class, shell flavour: the banner sits inside a
			// single-quoted `hdr='...'` string. Shape of
			// runtime/race/mkcgo.sh. Line 3 (`hdr='`) ends the header block.
			name: "generator-script/shell-banner-inside-string",
			head: "#!/bin/bash\n" +
				"\n" +
				"hdr='\n" +
				"// Copyright 2022 The Example Authors.\n" +
				"// Code generated by mkcgo.sh. DO NOT EDIT.\n" +
				"'\n",
		},
		{
			// CLASS 2 — DOCUMENTATION about the marker. Shape of
			// aws-sdk-go-v2/.github/PULL_REQUEST_TEMPLATE.md, which quotes the
			// banner inside a fenced code block at line 5 to tell contributors
			// what NOT to edit. Line 1 is a markdown heading (a `#` lead, so it
			// reads as a comment line); line 3 is prose and ends the block.
			name: "documentation/markdown-quotes-the-marker",
			head: "# **PLEASE READ BEFORE CONTINUING**\n" +
				"\n" +
				"**DO NOT** submit pull requests that modify generated source files.\n" +
				"Generated source files always carry an identifying header:\n" +
				"\n" +
				"```\n" +
				"// Code generated by example-codegen DO NOT EDIT.\n" +
				"```\n",
		},
		{
			// CLASS 2 — a README describing a SIBLING file rather than itself.
			// Shape of internal/trace/traceviewer/static/README.md.
			name: "documentation/readme-describes-a-sibling-file",
			head: "## Resources for the trace viewer\n" +
				"\n" +
				"This directory holds helper files used to embed the viewer.\n" +
				"\n" +
				"The current resources were generated from upstream:\n" +
				"\n" +
				"    trace_viewer_full.html: this file was generated by the vulcanize tool\n",
		},
		{
			// CLASS 3 — the sharpest: a HAND-WRITTEN test driver whose
			// mid-function comment describes the DATA FILE it is about to
			// read, not itself. Shape of flatbuffers/tests/ts/JavaScriptTest.js.
			// Line 2 (`import ...`) ends the header block.
			name: "test-driver/js-comment-about-a-data-file",
			head: "// Run this using JavaScriptTest.sh\n" +
				"import assert from 'assert'\n" +
				"import fs from 'fs'\n" +
				"\n" +
				"function main() {\n" +
				"  // First, let's test reading a FlatBuffer generated by C++ code:\n" +
				"  // This file was generated from monsterdata_test.json\n" +
				"  var data = new Uint8Array(fs.readFileSync('../monsterdata_test.mon'));\n" +
				"}\n",
		},
		{
			// CLASS 3 — PHP flavour of the same driver. `<?php` is a language
			// preamble and does NOT end the block; line 3 (`require ...`) does.
			// Shape of flatbuffers/tests/phpTest.php.
			name: "test-driver/php-comment-about-a-data-file",
			head: "<?php\n" +
				"// manual load for testing.\n" +
				"require join(DIRECTORY_SEPARATOR, array(dirname(__FILE__), \"Table.php\"));\n" +
				"\n" +
				"function main()\n" +
				"{\n" +
				"    // First, let's test reading a FlatBuffer generated by C++ code:\n" +
				"    // This file was generated from monsterdata_test.json\n" +
				"}\n",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if d := FromContent([]byte(tc.head)); d.Generated {
				t.Fatalf("false positive: rule %q fired on hand-written source:\n%s", d.Rule, tc.head)
			}
		})
	}
}

// TestFromContent_LanguagePreamblesDoNotEndTheHeaderBlock keeps the narrowing
// from over-reaching. A shebang, an XML declaration and a PHP open tag are all
// REQUIRED to precede the banner in their respective languages, so treating
// them as block terminators would blind the detector to real generator output.
//
// MUTATION TARGET: remove any preamble prefix from headerLine and the matching
// case here fails.
func TestFromContent_LanguagePreamblesDoNotEndTheHeaderBlock(t *testing.T) {
	cases := []struct {
		name string
		head string
		rule string
	}{
		{
			// protoc's PHP output: `<?php` must be line 1.
			name: "php/protoc",
			head: "<?php\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\n# source: user.proto\n",
			rule: "marker:protoc",
		},
		{
			// XSD-generated XAML/resx: the XML declaration precedes the banner.
			name: "xml/auto-generated-tag",
			head: "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- <auto-generated> -->\n<root>\n",
			rule: "marker:auto-generated-tag",
		},
		{
			// A generated shell script keeps its shebang on line 1.
			name: "shell/shebang-then-banner",
			head: "#!/bin/sh\n# Code generated by example-gen. DO NOT EDIT.\n\necho hi\n",
			rule: "marker:go-do-not-edit",
		},
		{
			// A UTF-8 BOM must not blind the very first line.
			name: "bom/then-banner",
			head: "\xef\xbb\xbf// Code generated by example-gen. DO NOT EDIT.\npackage foo\n",
			rule: "marker:go-do-not-edit",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			d := FromContent([]byte(tc.head))
			if !d.Generated {
				t.Fatalf("real generator banner missed:\n%s", tc.head)
			}
			if d.Rule != tc.rule {
				t.Fatalf("provenance = %q, want %q", d.Rule, tc.rule)
			}
		})
	}
}

// TestMarkers_ToolGeneratedRequiresACommentLead pins the second half of the
// false-positive fix. "This file was generated" is ordinary English, so unlike
// the other markers it must not fire on a bare prose line — only on a line
// that is unambiguously a comment. The other markers keep the optional lead
// because their text ("Code generated ... DO NOT EDIT.", "<auto-generated") is
// not something a person writes by accident.
//
// MUTATION TARGET: restore the `?` on commentLeadRequired and this fails.
func TestMarkers_ToolGeneratedRequiresACommentLead(t *testing.T) {
	// Bare prose, first line, inside the header block by construction.
	if d := FromContent([]byte("This file was generated from the schema in docs/.\n")); d.Generated {
		t.Fatalf("bare prose matched tool-generated (rule %q)", d.Rule)
	}
	// With a comment lead it must still fire — the jOOQ / openapi-typescript case.
	if d := FromContent([]byte("/*\n * This file is generated by jOOQ.\n */\n")); !d.Generated {
		t.Fatal("commented tool-generated banner was missed")
	}
}

// TestDetector_DoesNotFlagItself is the smallest honest end-to-end check that
// exists for this package: its OWN sources quote every marker it looks for,
// verbatim, dozens of times. If the detector flagged them it would be
// self-refuting, and the failure would be silent — nothing else in the suite
// reads a real file off disk.
//
// It is asserted rather than merely observed because the property is fragile
// in exactly one direction: any future widening of the scan window (dropping
// headerBlock, raising headScanLines past the package doc, making the markers
// case-insensitive) re-flags these files immediately.
func TestDetector_DoesNotFlagItself(t *testing.T) {
	// Repo-relative paths, so the filename table is exercised too.
	files := []string{
		"internal/generated/generated.go",
		"internal/generated/generated_6329_test.go",
		"docs/generated-source-patterns.md",
	}
	for _, rel := range files {
		t.Run(rel, func(t *testing.T) {
			onDisk := filepath.Join("..", "..", filepath.FromSlash(rel))
			content, err := os.ReadFile(onDisk)
			if err != nil {
				t.Fatalf("read %s: %v", onDisk, err)
			}
			if !bytes.Contains(content, []byte("DO NOT EDIT")) &&
				!bytes.Contains(content, []byte("auto-generated")) {
				t.Fatalf("%s no longer quotes any marker; this test has gone vacuous", rel)
			}
			if d := Detect(rel, content); d.Generated {
				t.Fatalf("the detector flags its own source %s (rule %q)", rel, d.Rule)
			}
		})
	}
}
