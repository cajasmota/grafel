// TestRuleTable_EveryRuleCarriesPositiveAndNegativeCases is hazard 5 from
// docs/generated-source-patterns.md turned into a gate: 63% of the deleted
// config's patterns could never match and nobody noticed, because no pattern
// had a test. A rule without both a positive and a negative case cannot be
// added to the table.
//
// MUTATION TARGET: delete the Negative slice from any rule and this must fail.
func TestRuleTable_EveryRuleCarriesPositiveAndNegativeCases(t *testing.T) {
	if len(pathRules) == 0 {
		t.Fatal("pathRules is empty; the table-driven gate would vacuously pass")
	}
	for _, r := range pathRules {
		if len(r.Positive) == 0 {
			t.Errorf("rule %q has no positive case", r.Pattern)
		}
		if len(r.Negative) == 0 {
			t.Errorf("rule %q has no negative case", r.Pattern)
		}
		if r.Generator == "" {
			t.Errorf("rule %q has no generator provenance", r.Pattern)
		}
	}
}

// TestRuleTable_CasesHoldRunsEveryRule's OWN cases through the public matcher.
// A positive case must be matched by ITS rule (not merely by some rule); a
// negative case must be matched by NO rule in the table.
func TestRuleTable_CasesHold(t *testing.T) {
	for _, r := range pathRules {
		for _, p := range r.Positive {
			if !matchPattern(r.Pattern, p) {
				t.Errorf("rule %q does not match its own positive case %q", r.Pattern, p)
			}
			d := FromPath(p)
			if !d.Generated {
				t.Errorf("FromPath(%q) = not generated, want generated via %q", p, r.Pattern)
			}
		}
		for _, n := range r.Negative {
			if d := FromPath(n); d.Generated {
				t.Errorf("FromPath(%q) = generated via %q, want not generated (negative case of rule %q)",
					n, d.Rule, r.Pattern)
			}
		}
	}
}

