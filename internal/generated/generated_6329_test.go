// TestFromContent_RealGeneratorHeaders pins the marker set against headers
// taken verbatim from generators observed on real repositories, not invented
// for the test. Provenance for each is in the case name.
func TestFromContent_RealGeneratorHeaders(t *testing.T) {
	cases := []struct {
		name string
		head string
		rule string
	}{
		{
			// internal/graph/fbgraph/Entity.go in this repository.
			name: "go/flatc",
			head: "// Code generated by the FlatBuffers compiler. DO NOT EDIT.\n\npackage fbgraph\n",
			rule: "marker:go-do-not-edit",
		},
		{
			// protoc-gen-go emits three header lines; DO NOT EDIT. is on the first.
			name: "go/protoc-gen-go",
			head: "// Code generated by protoc-gen-go. DO NOT EDIT.\n// versions:\n//  protoc-gen-go v1.31.0\n",
			rule: "marker:go-do-not-edit",
		},
		{
			// gomock. Covered by the marker, which is why PR1 carries no
			// mock_*.go filename rule (it collides with hand-written fakes).
			name: "go/mockgen",
			head: "// Code generated by MockGen. DO NOT EDIT.\n// Source: internal/foo/bar.go\n",
			rule: "marker:go-do-not-edit",
		},
		{
			// #6321 — WSDL/XSD partial classes that match neither
			// *.Designer.vb nor Reference.vb. This is the category two rounds
			// of filename counting missed.
			name: "vbnet/wsdl-partial",
			head: "'------------------------------------------------------------------------------\n' <auto-generated>\n'     This code was generated by a tool.\n' </auto-generated>\n",
			rule: "marker:auto-generated-tag",
		},
		{
			name: "csharp/designer",
			head: "//------------------------------------------------------------------------------\n// <auto-generated>\n//     This code was generated by a tool.\n// </auto-generated>\n",
			rule: "marker:auto-generated-tag",
		},
		{
			name: "python/protoc",
			head: "# -*- coding: utf-8 -*-\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\n# source: user.proto\n",
			rule: "marker:protoc",
		},
		{
			// testdata/fixtures/sources/java/jooq/Tables.java in this repository.
			name: "java/jooq",
			head: "/*\n * This file is generated by jOOQ.\n */\npackage com.example.db;\n",
			rule: "marker:tool-generated",
		},
		{
			// openapi-typescript, observed on the measurement corpus.
			name: "typescript/openapi",
			head: "/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n",
			rule: "marker:tool-generated",
		},
		{
			// Facebook/Meta convention, also used by Relay and graphql-codegen.
			name: "javascript/at-generated",
			head: "/**\n * @generated SignedSource<<0123456789abcdef>>\n * @flow\n */\n",
			rule: "marker:at-generated",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			d := FromContent([]byte(tc.head))
			if !d.Generated {
				t.Fatalf("marker not detected in header:\n%s", tc.head)
			}
			if d.Rule != tc.rule {
				t.Fatalf("provenance = %q, want %q", d.Rule, tc.rule)
			}
		})
	}
}

// TestFromContent_HandWrittenNearMisses is the false-positive guard, and every
// case is a REAL hand-written file, not an invented one. A naive
// case-insensitive substring scan of the first 20 lines flags all of these.
//
// MUTATION TARGET: widen the marker regexes to case-insensitive, or drop the
// comment-lead anchor, and this test must fail. If it still passes, the
// anchoring is not doing the work it is claimed to do.
func TestFromContent_HandWrittenNearMisses(t *testing.T) {
	cases := []struct {
		name string
		head string
	}{
		{
			// JPA. Case-insensitive `@generated` matches `@GeneratedValue` and
			// flags 101 hand-written entity classes on the measurement corpus
			// — the single largest false-positive source found.
			name: "java/jpa-GeneratedValue",
			head: "package com.example.model;\n\nimport jakarta.persistence.*;\n\n@Entity\npublic class User {\n    @Id\n    @GeneratedValue(strategy = GenerationType.IDENTITY)\n    private Long id;\n}\n",
		},
		{
			// internal/extractors/migration_prune.go in this repository: prose
			// ABOUT generated files, in a hand-written file.
			name: "go/prose-about-generated-files",
			head: "// migration_prune.go — central prune of Django migration entities.\n//\n// Background\n//\n// Auto-generated Django migration files (`<app>/migrations/0NNN_*.py`) are\n// pruned at the indexer level (#2706).\npackage extractors\n",
		},
		{
			// internal/daemon/watch/quarantine_content.go and
			// internal/custom/golang/sqlc.go: hand-written detectors that
			// carry the marker text inside a string literal.
			name: "go/marker-inside-string-literal",
			head: "package watch\n\nvar generatedHeader = []byte(\"// Code generated by\")\n\nfunc looksGenerated(b []byte) bool {\n\treturn bytes.HasPrefix(b, generatedHeader)\n}\n",
		},
		{
			// Lowercase `do not edit.` without the generator clause is a plain
			// warning, not a generator stamp.
			name: "go/bare-do-not-edit-warning",
			head: "// This file is load-bearing. DO NOT EDIT unless you have read #6329.\npackage foo\n",
		},
		{
			name: "python/docstring-mentions-generated",
			head: "\"\"\"Helpers for reading generated protobuf modules.\n\nThe code generated by protoc lives under proto/.\n\"\"\"\nimport os\n",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if d := FromContent([]byte(tc.head)); d.Generated {
				t.Fatalf("false positive: rule %q fired on hand-written source:\n%s", d.Rule, tc.head)
			}
		})
	}
}

// TestFromContent_ScanIsBoundedToHead pins the scan window. A marker below the
// window is NOT detected — that is the fail-safe direction (treated as
// hand-written) and it is what stops the scan cost scaling with file size.
func TestFromContent_ScanIsBoundedToHead(t *testing.T) {
	marker := "// Code generated by protoc-gen-go. DO NOT EDIT.\n"

	within := strings.Repeat("// filler\n", headScanLines-1) + marker
	if d := FromContent([]byte(within)); !d.Generated {
		t.Fatalf("marker on line %d (inside the %d-line window) was missed", headScanLines, headScanLines)
	}

	beyond := strings.Repeat("// filler\n", headScanLines+5) + marker
	if d := FromContent([]byte(beyond)); d.Generated {
		t.Fatalf("marker beyond the %d-line window was detected; scan is unbounded", headScanLines)
	}

	// Byte cap: a file whose first line alone exceeds the byte budget must not
	// be scanned past it (a minified bundle is one enormous line).
	longLine := strings.Repeat("x", headScanBytes+10) + "\n" + marker
	if d := FromContent([]byte(longLine)); d.Generated {
		t.Fatalf("marker beyond the %d-byte cap was detected; byte cap not enforced", headScanBytes)
	}
}

func TestFromContent_EmptyAndNil(t *testing.T) {
	if d := FromContent(nil); d.Generated {
		t.Fatalf("nil content reported generated (rule %q)", d.Rule)
	}
	if d := FromContent([]byte{}); d.Generated {
		t.Fatalf("empty content reported generated (rule %q)", d.Rule)
	}
}

