// TestDetect_MarkerAloneIsSufficient records the decision from #6329's second
// comment: a marker alone flips a file to generated. It never flips a file to
// skip, so the worst case of a wrong marker is a demoted ranking, not a
// missing entity.
func TestDetect_MarkerAloneIsSufficient(t *testing.T) {
	// A filename no rule in the table matches...
	if d := FromPath("Services/AccountsSoapClient.vb"); d.Generated {
		t.Fatalf("precondition failed: path already matches rule %q", d.Rule)
	}
	// ...still detects, on the marker alone.
	head := []byte("' <auto-generated>\n'     This code was generated by a tool.\n' </auto-generated>\n")
	d := Detect("Services/AccountsSoapClient.vb", head)
	if !d.Generated {
		t.Fatal("marker alone did not flip the file to generated")
	}
	if d.Rule != "marker:auto-generated-tag" {
		t.Fatalf("provenance = %q, want the marker rule", d.Rule)
	}
}

// TestDetect_PathAloneIsSufficient — the other half. Some generators emit no
// header at all (protoc-gen-go-grpc's *_grpc.pb.go historically did not).
func TestDetect_PathAloneIsSufficient(t *testing.T) {
	d := Detect("api/v1/user.pb.go", []byte("package v1\n\ntype User struct{}\n"))
	if !d.Generated {
		t.Fatal("filename rule alone did not flip the file to generated")
	}
	if !strings.HasPrefix(d.Rule, "path:") {
		t.Fatalf("provenance = %q, want a path: rule", d.Rule)
	}
}

// TestDetect_PathWinsProvenanceWhenBothFire keeps provenance deterministic.
// Without a stated order the reported rule depends on evaluation order, and
// provenance that varies run to run is not diagnosable in the field.
func TestDetect_PathWinsProvenanceWhenBothFire(t *testing.T) {
	head := []byte("// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage v1\n")
	d := Detect("api/v1/user.pb.go", head)
	if !d.Generated {
		t.Fatal("both signals present but not detected")
	}
	if d.Rule != "path:*.pb.go" {
		t.Fatalf("provenance = %q, want %q (path is evaluated first)", d.Rule, "path:*.pb.go")
	}
}

