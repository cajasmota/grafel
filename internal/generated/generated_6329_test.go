// TestMatchPattern_StatedSemantics pins the matcher itself. Hazard 5:
// "Match semantics must be chosen, not inherited." filepath.Match has no **
// and does not cross separators, which made 155 of the deleted config's 247
// parsed patterns permanently inert.
//
// MUTATION TARGET: swap matchPattern's body for filepath.Match and the ** and
// path-anchored cases must fail.
func TestMatchPattern_StatedSemantics(t *testing.T) {
	cases := []struct {
		pattern string
		path    string
		want    bool
		why     string
	}{
		// A pattern with no separator matches the BASENAME at any depth.
		{"*.pb.go", "api/v1/user.pb.go", true, "basename glob matches at depth"},
		{"*.pb.go", "user.pb.go", true, "basename glob matches at root"},
		{"wire_gen.go", "internal/di/wire_gen.go", true, "exact basename at depth"},
		{"wire_gen.go", "internal/di/wire_gen_test.go", false, "exact basename is not a prefix match"},

		// * does not cross a separator.
		{"api/*.pb.go", "api/user.pb.go", true, "* matches within one segment"},
		{"api/*.pb.go", "api/v1/user.pb.go", false, "* must not cross /"},

		// ** crosses separators, and **/ also matches zero directories.
		{"**/__generated__/**", "src/gql/__generated__/types.ts", true, "** crosses /"},
		{"**/__generated__/**", "__generated__/types.ts", true, "**/ matches zero leading dirs"},
		{"**/__generated__/**", "src/generated/types.ts", false, "literal segment must match"},

		// A leading / anchors at the repository root.
		{"/db/schema.rb", "db/schema.rb", true, "leading / anchors at repo root"},
		{"/db/schema.rb", "engines/blog/db/schema.rb", false, "anchored pattern does not match at depth"},

		// Glob metacharacters in the path must not be interpreted.
		{"*.pb.go", "a[b.pb.go", true, "path metacharacters are literal"},
	}
	for _, tc := range cases {
		t.Run(tc.pattern+"__"+tc.path, func(t *testing.T) {
			if got := matchPattern(tc.pattern, tc.path); got != tc.want {
				t.Fatalf("matchPattern(%q, %q) = %v, want %v (%s)",
					tc.pattern, tc.path, got, tc.want, tc.why)
			}
		})
	}
}

