// ---------------------------------------------------------------------------
// Marker regex properties, bound individually
// ---------------------------------------------------------------------------
//
// TestFromContent_HandWrittenNearMisses covers the real files, but each of its
// cases is defended by MORE THAN ONE property of the regexes, so no single
// mutation kills it. The JPA case is the clearest example: `@GeneratedValue`
// is rejected by case-sensitivity AND by the word boundary, independently.
// That is good defence-in-depth and bad test feedback — a mutant that removes
// one of the two survives while the guarantee is materially weaker.
//
// The three tests below bind one property each, so each has a mutant that
// kills it alone.

// TestMarkers_AreCaseSensitive binds case-sensitivity.
//
// MUTATION: change (?m) to (?im) in commentLead — this test must fail.
func TestMarkers_AreCaseSensitive(t *testing.T) {
	lowered := []string{
		"// code generated by protoc-gen-go. do not edit.\n",
		"// <AUTO-GENERATED>\n",
		"# generated by the Protocol Buffer Compiler\n",
		"/* this file is generated by jOOQ. */\n",
	}
	for _, s := range lowered {
		if d := FromContent([]byte(s)); d.Generated {
			t.Errorf("case-folded banner matched rule %q; markers are not case-sensitive: %q", d.Rule, s)
		}
	}
}

// TestMarkers_AtGeneratedRequiresWordBoundary binds the \b on @generated.
//
// The real-world driver is JPA's @GeneratedValue, which a scan without the
// boundary flags on 101 hand-written entity classes on the measurement corpus.
// The case here keeps the marker's exact casing so that case-sensitivity
// cannot be what rejects it — only the boundary can.
//
// MUTATION: drop \b from the at-generated marker — this test must fail.
func TestMarkers_AtGeneratedRequiresWordBoundary(t *testing.T) {
	suffixed := []string{
		"// @generatedValue(strategy = IDENTITY)\n",
		"// @generatedBy(\"hand\")\n",
	}
	for _, s := range suffixed {
		if d := FromContent([]byte(s)); d.Generated {
			t.Errorf("@generated matched as a prefix of a longer token (rule %q): %q", d.Rule, s)
		}
	}
	// The bare token still matches — the boundary must not break detection.
	if d := FromContent([]byte("// @generated\n")); !d.Generated {
		t.Fatal("word boundary broke detection of the bare @generated marker")
	}
}

// TestMarkers_RequireLineAnchor binds the (?m)^ anchor.
//
// A marker that appears after code on the same line is a string literal or a
// piece of prose, not a generator banner. Hand-written detectors in this
// repository (internal/daemon/watch/quarantine_content.go,
// internal/custom/golang/sqlc.go) carry the banner text in exactly that
// position.
//
// MUTATION: remove ^ from commentLead — this test must fail.
func TestMarkers_RequireLineAnchor(t *testing.T) {
	inline := []string{
		"package watch\n\nvar banner = \"// Code generated by protoc. DO NOT EDIT.\"\n",
		"const tag = `<auto-generated>`\n",
		"x := 1 // @generated\n",
	}
	for _, s := range inline {
		if d := FromContent([]byte(s)); d.Generated {
			t.Errorf("marker matched away from the line start (rule %q): %q", d.Rule, s)
		}
	}
}

