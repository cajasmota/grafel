// #6329 — detection of machine-generated source.
//
// The two halves are tested separately because they fail in opposite
// directions: a filename rule produces false POSITIVES (that is what killed
// the #6330 config, which would have eaten every *_test.go), while a content
// marker fails safe — a missed marker means the file is treated as
// hand-written, i.e. the status quo.

