package generated

import "testing"

// #6348 — a generated banner sitting behind a leading STATEMENT.
//
// #6345 narrowed the marker scan to the file's first contiguous comment block,
// which killed 38 measured false positives. The cost it recorded on FromContent
// is that any non-comment line — `set -e`, `using System;`, `Imports System` —
// closes the window before the banner is reached, so the file reads as
// hand-written. The observed instance is tetratelabs/wazero's
// site/static/install.sh: shebang, licence block, `set -e` on line 16, and the
// godownloader banner on line 17. goreleaser/godownloader stamps that layout
// across an ecosystem, not one file.
//
// The fix is a BOUNDED SKIP, not a wider headerLinePrefixes. Enumerating the
// leading statements per language (`set -e`, `using`, `Imports`, `declare`, …)
// makes every unlisted form silently invisible, which is the #6344 failure
// shape; the comment on FromContent already records that rejection. A bound
// says "a banner may sit behind a couple of statements" without naming them.
//
// MUTATION TARGET: set headerSkipBudget to 0 (or delete the skip branch in
// headerBlock) and every case here fails.
func TestFromContent_BannerBehindLeadingStatements(t *testing.T) {
	cases := []struct {
		name string
		head string
		rule string
	}{
		{
			// The observed case, reduced: godownloader/goreleaser install.sh.
			name: "shell/set-e-before-banner",
			head: "#!/bin/sh\n" +
				"set -e\n" +
				"# Code generated by godownloader. DO NOT EDIT.\n" +
				"\n" +
				"usage() { echo usage; }\n",
			rule: "marker:go-do-not-edit",
		},
		{
			// Full wazero shape: shebang, licence block, blank, `set -e`.
			name: "shell/licence-block-then-set-e",
			head: "#!/bin/sh\n" +
				"# Copyright 2020 The Example Authors.\n" +
				"# Licensed under the Apache License, Version 2.0.\n" +
				"#\n" +
				"# You may obtain a copy of the License at\n" +
				"#     http://www.apache.org/licenses/LICENSE-2.0\n" +
				"\n" +
				"set -euo pipefail\n" +
				"# Code generated by godownloader. DO NOT EDIT.\n",
			rule: "marker:go-do-not-edit",
		},
		{
			// Python: a triple-quoted module docstring. `\"\"\"` is not in
			// headerLinePrefixes at all, so today the block closes on line 1.
			name: "python/module-docstring-before-banner",
			head: "\"\"\"\n" +
				"Protocol buffer bindings for the widget service.\n" +
				"\"\"\"\n" +
				"\n" +
				"# Generated by the protocol buffer compiler.  DO NOT EDIT!\n" +
				"# source: widget.proto\n",
			rule: "marker:protoc",
		},
		{
			// Python: the __future__ import must precede everything but the
			// docstring, so a generator that emits it puts it before the banner.
			name: "python/from-future-import-before-banner",
			head: "from __future__ import annotations\n" +
				"\n" +
				"# Code generated by openapi-python-client. DO NOT EDIT.\n" +
				"\n" +
				"import attr\n",
			rule: "marker:go-do-not-edit",
		},
		{
			// C#: the designer emits usings above the auto-generated block.
			name: "csharp/using-before-auto-generated",
			head: "using System;\n" +
				"\n" +
				"//------------------------------------------------------------------------------\n" +
				"// <auto-generated />\n" +
				"//------------------------------------------------------------------------------\n",
			rule: "marker:auto-generated-tag",
		},
		{
			// VB.NET: `Imports System` before the auto-generated block. VB
			// designer files are the next cycle's target, so this shape has to
			// be reachable.
			name: "vbnet/imports-before-auto-generated",
			head: "Imports System\n" +
				"\n" +
				"'------------------------------------------------------------------------------\n" +
				"' <auto-generated>\n" +
				"'     This code was generated by a tool.\n" +
				"' </auto-generated>\n" +
				"'------------------------------------------------------------------------------\n",
			rule: "marker:auto-generated-tag",
		},
		{
			// Kotlin: a file-level annotation must precede the package line.
			name: "kotlin/file-suppress-annotation-before-banner",
			head: "@file:Suppress(\"UNCHECKED_CAST\", \"RedundantVisibilityModifier\")\n" +
				"\n" +
				"// Code generated by SqlDelight. DO NOT EDIT.\n" +
				"\n" +
				"package com.example.db\n",
			rule: "marker:go-do-not-edit",
		},
		{
			// PHP: strict_types must be the first statement in the file.
			name: "php/declare-strict-types-before-banner",
			head: "<?php\n" +
				"declare(strict_types=1);\n" +
				"\n" +
				"// This file is auto-generated by jane-php. DO NOT EDIT.\n" +
				"\n" +
				"namespace Acme\\Generated;\n",
			rule: "marker:tool-generated",
		},
		{
			// Java: the language REQUIRES package first, and generators emit
			// their imports before the class-level banner.
			name: "java/package-and-imports-before-banner",
			head: "package com.example.generated;\n" +
				"\n" +
				"import java.util.List;\n" +
				"import java.util.Map;\n" +
				"\n" +
				"// Code generated by wsdl2java. DO NOT EDIT.\n" +
				"public class Widget {}\n",
			rule: "marker:go-do-not-edit",
		},
		{
			// SQL: a migration generator emits the USE before its banner.
			name: "sql/banner-after-use-statement",
			head: "USE analytics;\n" +
				"\n" +
				"-- Code generated by sqlc. DO NOT EDIT.\n" +
				"-- source: query.sql\n",
			rule: "marker:go-do-not-edit",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			d := FromContent([]byte(tc.head))
			if !d.Generated {
				t.Fatalf("missed generated banner behind a leading statement:\n%s", tc.head)
			}
			if d.Rule != tc.rule {
				t.Fatalf("rule = %q, want %q", d.Rule, tc.rule)
			}
		})
	}
}

// TestFromContent_SkipBudgetIsBounded pins the bound itself. Two non-comment
// lines are skipped; the third closes the header block. Without a ceiling the
// change degenerates into "scan the whole head", which is exactly the #6329
// behaviour #6345 removed.
//
// MUTATION TARGET: raise headerSkipBudget and the third case starts matching.
func TestFromContent_SkipBudgetIsBounded(t *testing.T) {
	banner := "// Code generated by example-gen. DO NOT EDIT.\n"
	stmt := "call_something();\n"
	cases := []struct {
		name string
		head string
		want bool
	}{
		{"one-statement", stmt + banner, true},
		{"two-statements", stmt + stmt + banner, true},
		{"three-statements", stmt + stmt + stmt + banner, false},
		{"blank-lines-do-not-consume-the-budget", stmt + "\n\n\n" + stmt + "\n" + banner, true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := FromContent([]byte(tc.head)).Generated; got != tc.want {
				t.Fatalf("Generated = %v, want %v for:\n%s", got, tc.want, tc.head)
			}
		})
	}
}

// TestFromContent_ProseAndBodyLinesAreNotSkippable pins the other two clauses
// of skippableStatement. Both are load-bearing: with a bare line budget the
// #6345 markdown/README false positives and the flatbuffers JS test driver all
// come back, because their next line is "just a line" too.
//
// MUTATION TARGET: raise maxStatementWords past 7, or drop the `{` clause, and
// the matching case here fails (as do the #6329 false-positive cases).
func TestFromContent_ProseAndBodyLinesAreNotSkippable(t *testing.T) {
	banner := "// Code generated by example-gen. DO NOT EDIT.\n"
	cases := []struct {
		name string
		head string
	}{
		{
			// Prose: an English sentence is not a leading statement. Shape of
			// the aws-sdk PULL_REQUEST_TEMPLATE, which quotes the banner to
			// tell contributors what not to edit.
			name: "prose/sentence-closes-the-block",
			head: "Generated source files always carry an identifying header:\n" + banner,
		},
		{
			// Body: once a brace opens, everything below is code. Shape of
			// flatbuffers' JavaScriptTest.js, whose in-function comment
			// describes the data file it reads.
			name: "body/open-brace-closes-the-block",
			head: "function main() {\n" + banner,
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if d := FromContent([]byte(tc.head)); d.Generated {
				t.Fatalf("false positive: rule %q fired on:\n%s", d.Rule, tc.head)
			}
		})
	}
}

// TestFromContent_SkippedStatementOpeningAStringEndsTheBlock is the guard that
// keeps the bounded skip from re-admitting the sharpest #6345 false positive.
//
// runtime/race/mkcgo.sh is a HAND-WRITTEN generator script that assigns the
// banner it emits to a shell variable: `hdr='` on line 3 opens a multi-line
// single-quoted string, and lines 4-5 are that string's contents. A plain
// "skip up to N statements" would step over `hdr='` and read the banner inside
// the string — the exact regression this bound risks.
//
// The rule that stops it is not an exception for mkcgo.sh: a skipped statement
// that leaves a quote UNBALANCED means the following lines are string data,
// not header, so the block ends there. That is a structural statement, and it
// covers the perl heredoc sibling by the budget alone.
//
// MUTATION TARGET: drop the unbalanced-quote check and mkcgo.sh matches again.
func TestFromContent_SkippedStatementOpeningAStringEndsTheBlock(t *testing.T) {
	cases := []struct {
		name string
		head string
	}{
		{
			// Shape of runtime/race/mkcgo.sh, verbatim from the #6345 set.
			name: "shell/banner-inside-single-quoted-string",
			head: "#!/bin/bash\n" +
				"\n" +
				"hdr='\n" +
				"// Copyright 2022 The Example Authors.\n" +
				"// Code generated by mkcgo.sh. DO NOT EDIT.\n" +
				"'\n",
		},
		{
			// Double-quoted flavour of the same shape.
			name: "shell/banner-inside-double-quoted-string",
			head: "#!/bin/bash\n" +
				"\n" +
				"hdr=\"\n" +
				"// Code generated by mkcgo.sh. DO NOT EDIT.\n" +
				"\"\n",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if d := FromContent([]byte(tc.head)); d.Generated {
				t.Fatalf("false positive re-admitted: rule %q fired on:\n%s", d.Rule, tc.head)
			}
		})
	}
}
